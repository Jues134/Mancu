"""把「用户怎么说」翻译成「库里怎么存」。

条目标题是规范说法（《中国共产党的诞生》），用户的说法是口语：「党是怎么出来的」
「党的来历」「建党」「党从哪来」。这两种写法在二元组上几乎没有交集——「党是怎么
出来」切出来的是 党是/是怎/怎么/么出/出来，而条目标题切出来的是 中国/国共/共产/
产党/党的/的诞/诞生——所以靠调低阈值救不了：把 0.45 调到 0.1，所有主题会互相命中，
命中率上去了，正确率塌了。

正确做法是在检索**之前**做一次改写：认出「在问某个东西的由来」，把核心词抽出来，
配上库里真正会用的那几个词（诞生 / 成立 / 起源），拿改写后的词去匹配。

这里是纯规则，不调用模型：检索必须能在断网、无 key、模型不可用时工作，而这一步
是检索的前置条件。
"""

from __future__ import annotations

import re

#: 疑问句式的几种说法。`core` 是「用户在问谁」。
_PATTERNS = (
    # 党是怎么出来的 / 中国共产党是如何成立的 / 红军是怎样产生的
    re.compile(
        r"^(?P<core>.{1,14}?)"
        r"(?:到底|究竟)?"
        r"(?:是|为)?"
        r"(?:怎么|如何|怎样|咋)"
        r"(?:样|么样)?"
        r"(?:来|出来|来的|产生|出现|诞生|建立|成立|形成)?"
        r"(?:的|呢|啊)?$"
    ),
    # 党的来历 / 中共的由来 / 五四运动的起源
    re.compile(r"^(?P<core>.{1,14}?)(?:的|之)?(?:来历|由来|起源|源头|前身|前世今生|历史)$"),
    # 党从哪来 / 党从哪里来
    re.compile(r"^(?P<core>.{1,14}?)(?:从哪|从哪里|打哪)(?:里)?(?:来|来的)?(?:的)?$"),
)

#: 库里的标题会用这些词。顺序即尝试顺序：占多数的事件排前面。
_EVENTS = ("诞生", "成立", "起源")

#: 少数固定说法。只写确实知道指向哪一条的——猜错比不猜更糟，它会把用户带到
#: 另一条知识上，而错误的知识比没有知识更难发现。
ALIASES = {
    "建党": ("党的诞生", "中国共产党的诞生"),
    "党建": ("党的建设",),
    "红船": ("中共一大 嘉兴南湖",),
}


def core_of(query: str) -> str:
    """「党是怎么出来的」→「党」。认不出句式就返回空串。"""
    text = (query or "").strip()
    for pattern in _PATTERNS:
        match = pattern.match(text)
        if match:
            core = match.group("core").strip()
            # 只剩一个「的」「是」这种，等于没抽到东西。
            if core and core not in ("的", "是", "它", "这", "那"):
                return core
    return ""


def expand(query: str, *, limit: int = 6) -> list[str]:
    """候选检索词，越可能命中越靠前。**第一项永远是原句**。

    原句排第一，是因为它命中时最精确：用户说的话如果本来就和标题对得上，不该
    被改写过的版本抢走。
    """
    text = (query or "").strip()
    if not text:
        return []

    candidates: list[str] = [text]

    for alias, targets in ALIASES.items():
        if alias in text:
            candidates.extend(targets)

    core = core_of(text)
    if core:
        for event in _EVENTS:
            candidates.append(f"{core}的{event}")
        # 「党的诞生」和「党诞生」是两种真实存在的写法，各给一次机会。
        for event in _EVENTS:
            candidates.append(f"{core}{event}")

    out: list[str] = []
    for item in candidates:
        key = item.strip()
        if key and key not in out:
            out.append(key)
        if len(out) >= limit:
            break
    return out


#: 指令性填充词：它们描述的是「要什么样的成品」，不是「成品讲什么」。
#:
#: 这个表原先只在 `store._pairs` 里用——因为关键词检索会把填充词也切成二元组，
#: 于是「帮我」「做一个」「视频」各自贡献得分，把真正的主题稀释掉。但**向量检索
#: 一直在用原句嵌入**，同一个问题在那里从没被处理过：查「帮我做一个国民党一大的
#: 视频」时，送进嵌入接口的是整句，主题被「做视频」这个意图平均掉了。
#:
#: 实测差别（同一本书、同一个问题）：
#:   原句        → 章节块 0.4515，正文块没过阈值，只能定位到「1924 年」
#:   去掉填充词   → 正文块 0.6135，直接定位到「1924 年 · 国民党一大召开」
#: 0.16 的差距足以决定「找到那一章」还是「找到那一段」。
STOP_PHRASES = (
    "帮我", "做一个", "做一期", "生成", "制作", "视频", "短片", "片子", "关于",
    "大概", "左右", "分钟", "时长", "一下", "一个", "需要", "想要", "请",
    "一段", "两段", "几段",
)


def strip_filler(text: str) -> str:
    """去掉指令外壳，只留主题。用于**向量检索**的查询文本。

    不做句子成分分析，只做删除——因为这些词在中文里几乎只以固定形式出现在
    这类句式里，删除比"识别并保留核心"更不容易出错。删空的极端情况由调用方
    回退到原句（`strip_filler(x) or x`），不会把查询弄没。

    时长说明单独用正则处理：「3 分钟」「5 秒」不是固定词，写进词表会漏掉
    「8 分钟」「15 秒」。而它们和主题完全无关，留着只会稀释向量。
    """
    out = text or ""
    for phrase in STOP_PHRASES:
        out = out.replace(phrase, "")
    # 「3 分钟」「2 秒」：数字 + 时长单位，连同后面可能残留的「的」一起删。
    out = re.sub(r"\d+\s*(?:分钟|分|秒|小时|字|页)", "", out)
    out = re.sub(r"\d+\s*的", "", out)
    out = " ".join(out.split()).strip()
    # 删完之后常留一个悬空的「的」：开头（「的党史内容」）或结尾（「国民党一大的」）。
    return out.strip("的").strip()
