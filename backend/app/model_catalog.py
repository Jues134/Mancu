"""Scan a provider's model catalogue and classify each model by capability.

Requirement: the user supplies base_url + key, and the app lists what that key can
use — no model name typed by hand.

Design problem: `/v1/models` returns ids and nothing else. Neither Zhipu nor
SiliconFlow says "this one draws images". So classification has to come from the
id itself, and it has to be conservative: putting an image model in the text slot
produces a confusing failure at generation time.

Classification strategy, in order:

  1. **Known families** — a curated list of ids whose capability is established
     (verified against this project's own runs). Highest confidence.
  2. **Family-name patterns** — e.g. anything containing "Kolors", "cogview",
     "flux", "dall-e" is an image model; "cogvideo", "i2v", "wan" is video.
  3. **Capability hints in the id** — "vl", "vision" suggest vision.
  4. **Fallback: text** — a model that matches none of the above is assumed to be
     a text model, because that is the most common case and the least
     consequential mistake (a wrong text model fails loudly on the first call).

Every classification carries its reason, so the UI can show *why* a model was
placed in a group and a user can override it if the guess is wrong.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

#: Capability keys, matching what the generator and agents consume.
CAP_TEXT = "text"
CAP_VISION = "vision"
CAP_IMAGE = "image"
CAP_VIDEO = "video"

CAP_LABELS = {
    CAP_TEXT: "文本",
    CAP_VISION: "视觉",
    CAP_IMAGE: "生图",
    CAP_VIDEO: "生视频",
}

#: Verified ids. Each was exercised in this project, so the mapping is a fact
#: rather than a guess:
#:   · Kwai-Kolors/Kolors     → produced the portrait used in the README
#:   · cogview-4-250304       → produced probe images (1890×1080)
#:   · cogvideox-3            → produced the 5 s character video
#:   · glm-4v-flash           → the configured vision model
KNOWN = {
    "Kwai-Kolors/Kolors": CAP_IMAGE,
    "cogview-4-250304": CAP_IMAGE,
    "cogview-3-flash": CAP_IMAGE,
    "cogvideox-3": CAP_VIDEO,
    "cogvideox-2": CAP_VIDEO,
    "glm-4v-flash": CAP_VISION,
    "glm-4v-plus": CAP_VISION,
}

#: Substrings that identify an image model. Ordered longest-first so a specific
#: name wins over a generic one.
IMAGE_HINTS = (
    "kolors", "cogview", "flux", "dall-e", "dalle", "stable-diffusion",
    "sdxl", "z-image", "qwen-image", "seedream", "imagen", "grok-image",
)

#: Substrings that identify an image-to-video or text-to-video model.
VIDEO_HINTS = (
    "cogvideo", "i2v", "t2v", "image-to-video", "text-to-video",
    "kling", "hailuo", "seedance", "wan2", "wanx",
    # MiniMax ships video models under "MiniMax-H3" / "MiniMax-Video", but it is
    # first of all a chat vendor: a bare "minimax" marker filed 3 chat models
    # (minimax-m2.7 / m3 / m3.1-flash) under 生视频, so the settings page offered
    # them in the video slot and a run would have asked a chat model for an mp4.
    # Match the product names, not the vendor.
    "minimax-video", "minimax-h3", "abab-video",
    "video-01", "vidu", "runway", "pika", "luma",
)

#: Substrings that identify a model accepting image input.
VISION_HINTS = (
    "vl", "vision", "4v", "multi-modal", "multimodal", "llava", "internvl",
)


@dataclass
class ModelEntry:
    """One model in a provider's catalogue, with its inferred capability."""

    id: str
    capability: str = CAP_TEXT
    #: Why it was placed here, shown to the user so a wrong guess is correctable.
    reason: str = ""
    owned_by: str = ""

    def to_dict(self) -> dict[str, str]:
        return {
            "id": self.id,
            "capability": self.capability,
            "label": CAP_LABELS.get(self.capability, self.capability),
            "reason": self.reason,
            "owned_by": self.owned_by,
        }


@dataclass
class Catalogue:
    """Every model one key can use, grouped by capability."""

    entries: list[ModelEntry] = field(default_factory=list)
    #: Errors from scanning, surfaced rather than swallowed: a key that cannot
    #: list its models should say so instead of showing an empty list.
    error: str = ""
    #: Where the failure came from.  The settings API itself always answers 200
    #: for a completed probe; an upstream 400/502 belongs to the configured
    #: provider and must not look like a 400/502 generated by this application.
    error_source: str = ""
    upstream_status: int | None = None
    upstream_body: str = ""

    def group(self) -> dict[str, list[dict[str, str]]]:
        out: dict[str, list[dict[str, str]]] = {
            CAP_TEXT: [], CAP_VISION: [], CAP_IMAGE: [], CAP_VIDEO: []
        }
        for e in self.entries:
            out.setdefault(e.capability, []).append(e.to_dict())
        return out

    def counts(self) -> dict[str, int]:
        return {k: len(v) for k, v in self.group().items()}


def classify(model_id: str) -> tuple[str, str]:
    """Return (capability, reason) for one model id."""
    raw = (model_id or "").strip()
    low = raw.lower()

    if raw in KNOWN:
        return KNOWN[raw], "已确认"

    for hint in IMAGE_HINTS:
        if hint in low:
            return CAP_IMAGE, f"名称含「{hint}」"

    for hint in VIDEO_HINTS:
        if hint in low:
            return CAP_VIDEO, f"名称含「{hint}」"

    # Vision before text: "vl" is a reliable marker and the reverse would misfile
    # every multimodal model as text-only.
    for hint in VISION_HINTS:
        # Match as a whole word or a trailing segment to avoid "vl" inside
        # unrelated names.
        if re.search(rf"(^|[/_\-]){re.escape(hint)}($|[/_\-0-9])", low):
            return CAP_VISION, f"名称含「{hint}」"

    # 「glm-4v / glm-5v / qwen-2.5-vl」这类：数字 + v 是这一代厂商通用的视觉后缀。
    # 只写死 "4v" 会在下一代立刻失效——glm-5v-turbo 就是被当成文本模型的，而它
    # 一旦被分到文本槽，看图的 Agent 拿到的是「模型不支持图片」这类远端报错。
    if re.search(r"(^|[/_\-])\d+(?:\.\d+)?v($|[/_\-0-9])", low):
        return CAP_VISION, "名称含视觉后缀（数字+v）"

    return CAP_TEXT, "默认为文本模型"


def build(ids: list[str], owned_by: dict[str, str] | None = None) -> Catalogue:
    """Classify a list of ids into a catalogue."""
    cat = Catalogue()
    for mid in ids:
        if not mid:
            continue
        cap, why = classify(mid)
        cat.entries.append(
            ModelEntry(
                id=mid,
                capability=cap,
                reason=why,
                owned_by=(owned_by or {}).get(mid, ""),
            )
        )
    return cat
